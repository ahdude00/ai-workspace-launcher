using System.Collections.Concurrent;
using AWL.Core.Claude;
using AWL.Core.Common;
using AWL.Core.Terminal;

namespace AWL.Core.Sessions;

/// <summary>
/// Business rules of the session life cycle: creating, opening, resuming and reconciling sessions
/// (OTR-01–04, OTR-06–09, OTR-15, OTR-17, OTR-18, OTR-20; D12, D14).
/// </summary>
public sealed class SessionService : IDisposable
{
    /// <summary>The longest title accepted for a session.</summary>
    public const int MaxTitleLength = 200;

    // The process monitor polls every two seconds; a launch is treated as running until it can be observed.
    private static readonly TimeSpan LaunchGracePeriod = TimeSpan.FromSeconds(10);

    private readonly ISessionRepository _repository;
    private readonly ClaudeCommandBuilder _commandBuilder;
    private readonly ITerminalLauncher _terminal;
    private readonly IClaudeProcessMonitor _monitor;
    private readonly IClaudeHistoryStore _history;
    private readonly IClaudeInstallation _installation;
    private readonly IClock _clock;
    private readonly ConcurrentDictionary<Guid, DateTimeOffset> _recentLaunches = new();
    private readonly SemaphoreSlim _openGate = new(1, 1);

    public SessionService(ISessionRepository repository, ClaudeCommandBuilder commandBuilder, ITerminalLauncher terminal,
        IClaudeProcessMonitor monitor, IClaudeHistoryStore history, IClaudeInstallation installation, IClock clock)
    {
        _repository = repository;
        _commandBuilder = commandBuilder;
        _terminal = terminal;
        _monitor = monitor;
        _history = history;
        _installation = installation;
        _clock = clock;
        _monitor.Changed += (_, _) => Changed?.Invoke(this, EventArgs.Empty);
    }

    /// <summary>Raised when a session was changed or the set of running sessions changed.</summary>
    public event EventHandler? Changed;

    /// <summary>Calculates the current state of a stored session.</summary>
    public SessionState GetState(Session session)
    {
        ArgumentNullException.ThrowIfNull(session);
        return SessionStateResolver.Resolve(session, IsRunning(session), HistoryExists(session),
            session.LastErrorCode is not null);
    }

    /// <summary>Lists every session with its current state, newest first.</summary>
    public async Task<IReadOnlyList<SessionSnapshot>> ListAsync(CancellationToken cancellationToken = default)
    {
        var sessions = await _repository.ListAsync(cancellationToken).ConfigureAwait(false);
        return [.. sessions.Select(session => new SessionSnapshot(session, GetState(session)))];
    }

    /// <summary>Validates and stores a new session with a Claude session identifier generated by AWL (D14).</summary>
    /// <remarks>The session is not started; call <see cref="OpenAsync"/> to open it.</remarks>
    public async Task<Result<Session>> CreateAsync(string title, string workspacePath, Guid? categoryId,
        CancellationToken cancellationToken = default)
    {
        if (ValidateTitle(title) is { } titleError)
        {
            return Result.Fail<Session>(titleError);
        }
        if (ValidateWorkspace(workspacePath) is { } workspaceError)
        {
            return Result.Fail<Session>(workspaceError);
        }

        var session = new Session(Guid.NewGuid(), title.Trim(), categoryId, Path.GetFullPath(workspacePath),
            Guid.NewGuid(), null, false, _clock.UtcNow, null, null);
        await _repository.AddAsync(session, cancellationToken).ConfigureAwait(false);
        RaiseChanged();
        return Result.Ok(session);
    }

    /// <summary>
    /// Opens a session: a session never started gets <c>--session-id</c>, a started one <c>--resume</c>.
    /// An already running session is not started twice; its window is brought forward instead (OTR-08).
    /// </summary>
    public async Task<Result<OpenOutcome>> OpenAsync(Guid sessionId, CancellationToken cancellationToken = default)
    {
        await _openGate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            var session = await _repository.GetAsync(sessionId, cancellationToken).ConfigureAwait(false);
            if (session is null)
            {
                return Result.Fail<OpenOutcome>(Errors.SessionNotFound);
            }
            if (IsRunning(session))
            {
                await _monitor.TryBringToFrontAsync(session.ClaudeSessionId, cancellationToken).ConfigureAwait(false);
                return Result.Ok(OpenOutcome.AlreadyOpen);
            }
            if (!Directory.Exists(session.WorkspacePath))
            {
                return Result.Fail<OpenOutcome>(Errors.WorkspaceMissing);
            }

            LaunchMode mode = session.LastOpenedAt is null ? LaunchMode.New : LaunchMode.Resume;
            if (mode == LaunchMode.Resume && !HistoryExists(session))
            {
                return Result.Fail<OpenOutcome>(Errors.HistoryMissing);
            }
            return await LaunchAsync(session, mode, cancellationToken).ConfigureAwait(false);
        }
        finally
        {
            _openGate.Release();
        }
    }

    /// <summary>
    /// Starts a new Claude conversation in the same folder for a session whose history is gone (OTR-17).
    /// The AWL record, title and category are kept; Claude gets a new session identifier.
    /// </summary>
    public async Task<Result<OpenOutcome>> StartOverAsync(Guid sessionId, CancellationToken cancellationToken = default)
    {
        await _openGate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            var session = await _repository.GetAsync(sessionId, cancellationToken).ConfigureAwait(false);
            if (session is null)
            {
                return Result.Fail<OpenOutcome>(Errors.SessionNotFound);
            }
            if (IsRunning(session))
            {
                await _monitor.TryBringToFrontAsync(session.ClaudeSessionId, cancellationToken).ConfigureAwait(false);
                return Result.Ok(OpenOutcome.AlreadyOpen);
            }
            if (HistoryExists(session))
            {
                // Replacing the identifier would leave the existing transcript without an owner.
                return Result.Fail<OpenOutcome>(Errors.HistoryStillPresent);
            }
            if (!Directory.Exists(session.WorkspacePath))
            {
                return Result.Fail<OpenOutcome>(Errors.WorkspaceMissing);
            }

            var fresh = session with { ClaudeSessionId = Guid.NewGuid(), LastOpenedAt = null };
            if (!await _repository.UpdateAsync(fresh, cancellationToken).ConfigureAwait(false))
            {
                return Result.Fail<OpenOutcome>(Errors.SessionNotFound);
            }
            RaiseChanged();
            return await LaunchAsync(fresh, LaunchMode.New, cancellationToken).ConfigureAwait(false);
        }
        finally
        {
            _openGate.Release();
        }
    }

    /// <summary>Points a session whose working folder no longer exists to another folder (OTR-20).</summary>
    public async Task<Result<Session>> RelocateAsync(Guid sessionId, string workspacePath,
        CancellationToken cancellationToken = default)
    {
        if (ValidateWorkspace(workspacePath) is { } error)
        {
            return Result.Fail<Session>(error);
        }
        var session = await _repository.GetAsync(sessionId, cancellationToken).ConfigureAwait(false);
        if (session is null)
        {
            return Result.Fail<Session>(Errors.SessionNotFound);
        }

        var moved = session with { WorkspacePath = Path.GetFullPath(workspacePath) };
        if (!await _repository.UpdateAsync(moved, cancellationToken).ConfigureAwait(false))
        {
            return Result.Fail<Session>(Errors.SessionNotFound);
        }
        RaiseChanged();
        return Result.Ok(moved);
    }

    /// <summary>
    /// Startup reconciliation (OTR-15): the last activity of every session is taken from the modification
    /// time of its Claude transcript.
    /// </summary>
    /// <returns>The number of sessions whose stored activity time changed.</returns>
    public async Task<int> ReconcileAsync(CancellationToken cancellationToken = default)
    {
        var sessions = await _repository.ListAsync(cancellationToken).ConfigureAwait(false);
        int changed = 0;
        foreach (var session in sessions)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (FindHistory(session) is { } history && history.LastModifiedUtc != session.LastActivityAt
                && await _repository.UpdateAsync(session with { LastActivityAt = history.LastModifiedUtc },
                    cancellationToken).ConfigureAwait(false))
            {
                changed++;
            }
        }
        if (changed > 0)
        {
            RaiseChanged();
        }
        return changed;
    }

    private async Task<Result<OpenOutcome>> LaunchAsync(Session session, LaunchMode mode, CancellationToken cancellationToken)
    {
        var spec = _commandBuilder.Build(session, mode);
        var launched = await _terminal.LaunchAsync(spec, session.Title, cancellationToken).ConfigureAwait(false);
        if (!launched.IsSuccess)
        {
            return Result.Fail<OpenOutcome>(launched.Error);
        }

        DateTimeOffset now = _clock.UtcNow;
        _recentLaunches[session.ClaudeSessionId] = now;
        var opened = session with
        {
            LastOpenedAt = now,
            LastActivityAt = now,
            ClaudeVersion = _installation.Version ?? session.ClaudeVersion,
        };
        await _repository.UpdateAsync(opened, cancellationToken).ConfigureAwait(false);
        RaiseChanged();
        return Result.Ok(OpenOutcome.Launched);
    }

    private bool IsRunning(Session session)
    {
        if (_monitor.RunningSessionIds.Contains(session.ClaudeSessionId))
        {
            _recentLaunches.TryRemove(session.ClaudeSessionId, out _);
            return true;
        }
        if (_recentLaunches.TryGetValue(session.ClaudeSessionId, out var launchedAt))
        {
            if (_clock.UtcNow - launchedAt < LaunchGracePeriod)
            {
                return true;
            }
            _recentLaunches.TryRemove(session.ClaudeSessionId, out _);
        }
        return false;
    }

    // When the Claude folder cannot be read, the history is assumed to exist rather than reported missing.
    private bool HistoryExists(Session session)
    {
        try
        {
            return _history.Find(session.ClaudeSessionId) is not null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return true;
        }
    }

    private HistoryInfo? FindHistory(Session session)
    {
        try
        {
            return _history.Find(session.ClaudeSessionId);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return null;
        }
    }

    private static AppError? ValidateTitle(string title) =>
        string.IsNullOrWhiteSpace(title) || title.Trim().Length > MaxTitleLength ? Errors.TitleInvalid : null;

    private static AppError? ValidateWorkspace(string workspacePath)
    {
        if (string.IsNullOrWhiteSpace(workspacePath) || !Path.IsPathFullyQualified(workspacePath))
        {
            return Errors.WorkspaceInvalid;
        }
        return Directory.Exists(workspacePath) ? null : Errors.WorkspaceMissing;
    }

    public void Dispose() => _openGate.Dispose();

    private void RaiseChanged() => Changed?.Invoke(this, EventArgs.Empty);

    /// <summary>Error codes returned by <see cref="SessionService"/>; each code is also its resource key.</summary>
    public static class Errors
    {
        public static readonly AppError SessionNotFound = new("SessionNotFound", "SessionNotFound");
        public static readonly AppError TitleInvalid = new("SessionTitleInvalid", "SessionTitleInvalid");
        public static readonly AppError WorkspaceInvalid = new("WorkspaceInvalid", "WorkspaceInvalid");
        public static readonly AppError WorkspaceMissing = new("WorkspaceMissing", "WorkspaceMissing");
        public static readonly AppError HistoryMissing = new("HistoryMissing", "HistoryMissing");
        public static readonly AppError HistoryStillPresent = new("HistoryStillPresent", "HistoryStillPresent");
    }
}
